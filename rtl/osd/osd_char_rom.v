//======================================================================
// osd_char_rom.v
// 5x7 ASCII 点阵字库（OSD 屏幕菜单用）
//
// 设计说明：
//   - 每个字符 5 列 x 7 行，打包成 56bit（7 字节，行0在最高字节）
//   - 每行 8bit，5 列点阵放在 bit[4:0]（左对齐），bit[7:5] 恒为 0
//   - 纯组合逻辑生成，综合成分布式 ROM（LUT），约 300 LUT
//   - 字符集：空格、0-9、A-Z、常用符号（: / . - % > < = [ ] | _ , + ! ?）
//
// 复用说明：这是新增模块（原有工程无 OSD），与 color_bar 等完全解耦，
//           可在 video_clk 域被任意显示逻辑调用。
//======================================================================
module osd_char_rom (
    input  wire [7:0] i_ascii,    // ASCII 码（0x20 ~ 0x7F）
    input  wire [3:0] i_row,      // 字符内行号 0~15（5x7 字模占 0~6，7~15 空白）
    output reg  [7:0] o_row_data  // 该行 8bit 点阵（5 列在 bit[4:0]）
);

// 56bit = 7 字节：{row0, row1, row2, row3, row4, row5, row6}
reg [55:0] glyph;

always @(*) begin
    case (i_ascii)
        // ---------- 符号 ----------
        8'h20: glyph = 56'h00000000000000; // 空格
        8'h21: glyph = 56'h04040404040004; // !
        8'h25: glyph = 56'h19190204081313; // %
        8'h2B: glyph = 56'h0004041F040400; // +
        8'h2C: glyph = 56'h00000000000C04; // ,
        8'h2D: glyph = 56'h000000001F0000; // -
        8'h2E: glyph = 56'h00000000000C0C; // .
        8'h2F: glyph = 56'h01020204080810; // /
        // ---------- 数字 0-9 ----------
        8'h30: glyph = 56'h0E11131519110E; // 0
        8'h31: glyph = 56'h040C040404040E; // 1
        8'h32: glyph = 56'h0E11010204081F; // 2
        8'h33: glyph = 56'h1F02040201110E; // 3
        8'h34: glyph = 56'h02060A121F0202; // 4
        8'h35: glyph = 56'h1F101E0101110E; // 5
        8'h36: glyph = 56'h0608101E11110E; // 6
        8'h37: glyph = 56'h1F010204080808; // 7
        8'h38: glyph = 56'h0E11110E11110E; // 8
        8'h39: glyph = 56'h0E11110F01020C; // 9
        // ---------- 符号 ----------
        8'h3A: glyph = 56'h000C0C000C0C00; // :
        8'h3C: glyph = 56'h02040810080402; // <
        8'h3D: glyph = 56'h00001F001F0000; // =
        8'h3E: glyph = 56'h08040201020408; // >
        8'h3F: glyph = 56'h0E110102040004; // ?
        // ---------- 大写 A-Z ----------
        8'h41: glyph = 56'h0E11111F111111; // A
        8'h42: glyph = 56'h1E11111E11111E; // B
        8'h43: glyph = 56'h0E11101010110E; // C
        8'h44: glyph = 56'h1C12111111121C; // D
        8'h45: glyph = 56'h1F10101E10101F; // E
        8'h46: glyph = 56'h1F10101E101010; // F
        8'h47: glyph = 56'h0E11101711110F; // G
        8'h48: glyph = 56'h1111111F111111; // H
        8'h49: glyph = 56'h0E04040404040E; // I
        8'h4A: glyph = 56'h0702020202120C; // J
        8'h4B: glyph = 56'h11121418141211; // K
        8'h4C: glyph = 56'h1010101010101F; // L
        8'h4D: glyph = 56'h111B1515111111; // M
        8'h4E: glyph = 56'h11191513111111; // N
        8'h4F: glyph = 56'h0E11111111110E; // O
        8'h50: glyph = 56'h1E11111E101010; // P
        8'h51: glyph = 56'h0E11111115120D; // Q
        8'h52: glyph = 56'h1E11111E141211; // R
        8'h53: glyph = 56'h0F10100E01011E; // S
        8'h54: glyph = 56'h1F040404040404; // T
        8'h55: glyph = 56'h1111111111110E; // U
        8'h56: glyph = 56'h11111111110A04; // V
        8'h57: glyph = 56'h1111111515150A; // W
        8'h58: glyph = 56'h11110A040A1111; // X
        8'h59: glyph = 56'h11110A04040404; // Y
        8'h5A: glyph = 56'h1F01020408101F; // Z
        // ---------- 符号 ----------
        8'h5B: glyph = 56'h0E08080808080E; // [
        8'h5D: glyph = 56'h0E02020202020E; // ]
        8'h5F: glyph = 56'h0000000000001F; // _
        8'h7C: glyph = 56'h04040404040404; // |
        default: glyph = 56'h00000000000000; // 未知字符 → 空白
    endcase
end

// 行号 0~6 取字模，7~15 空白（用于 8x16 字符格纵向留白）
always @(*) begin
    if (i_row >= 4'd7)
        o_row_data = 8'h00;
    else
        o_row_data = glyph[((4'd6 - i_row) * 8) +: 8];
end

endmodule
