"""Rebuild the embedded SimHei menu font without changing the first 32 glyphs."""
from pathlib import Path
import argparse
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
ORIGINAL_CHARS = '欢迎光临电子相册参赛作品多媒体展示' + ' ' * 15
MENU_CHARS = '菜单播放暂停亮度对比伽马音量静诊断退出状态开关返回上下确认长按'
SYMBOLS = '0123456789 +-:'
EXTRA_CHARS = '图片视频乐分辨率一张段首×'
CHARS = ORIGINAL_CHARS + MENU_CHARS + SYMBOLS + EXTRA_CHARS


def glyph(ch, font):
    img = Image.new('1', (16, 16), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    return [sum((img.getpixel((x, y)) & 1) << (15-x) for x in range(16))
            for y in range(16)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', default=r'C:\Windows\Fonts\simhei.ttf')
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    target = ROOT / 'src/modules/osd'
    mem_file, rtl_file = target/'zh_font.mem', target/'zh_font_rom.v'
    old = [int(word, 16) for word in mem_file.read_text().split()]
    embedded = {int(i): int(v, 16) for i, v in re.findall(
        r"mem\[(\d+)\]=16'h([0-9a-fA-F]+);", rtl_file.read_text())}
    assert len(old) >= 512 and all(old[i] == embedded[i] for i in range(512))
    assert len(ORIGINAL_CHARS) == 32 and len(MENU_CHARS) == 31 and len(CHARS) == 90
    font = ImageFont.truetype(args.font, 16)
    # Existing artwork is authoritative, including blank reserved characters.
    words = old[:512] + [w for ch in CHARS[32:] for w in glyph(ch, font)]
    mem_file.write_text(''.join(f'{w:04x}\n' for w in words), encoding='ascii')
    lines = ['// SimHei 16x16: original 32 glyphs preserved; menu indices 32..89.',
             '// Generated by scripts/gen_zh_font.py; bit15 is the left pixel.',
             'module zh_font_rom #(parameter BANK=0)(input clk,input [6:0] char_idx,input [3:0] row,output reg [15:0] bits);',
             ' (* ram_style="bram" *) reg [15:0] mem[0:1439];', ' initial begin']
    lines += [f"  mem[{i}]=16'h{w:04x};" for i, w in enumerate(words)]
    lines += [' end', ' generate', ' if(BANK==1)begin:legacy_font',
              '  (* ram_style="bram" *) reg [15:0] legacy_words[0:511];',
              '  initial begin']
    lines += [f"   legacy_words[{i}]=16'h{w:04x};" for i,w in enumerate(words[:512])]
    lines += ['  end', '  always @(posedge clk)bits<=legacy_words[{char_idx[4:0],row}];',
              ' end else if(BANK==2)begin:menu_font',
              '  (* ram_style="bram" *) reg [15:0] menu_words[0:927];',
              "  wire [5:0] menu_index=char_idx-7'd32;", '  initial begin']
    lines += [f"   menu_words[{i}]=16'h{w:04x};" for i,w in enumerate(words[512:])]
    lines += ['  end', '  always @(posedge clk)bits<=menu_words[{menu_index,row}];',
              ' end else begin:full_font',
              '  always @(posedge clk)bits<=mem[{char_idx,row}];',
              ' end', ' endgenerate', 'endmodule']
    rtl_file.write_text('\n'.join(lines)+'\n', encoding='ascii')
    if args.preview:
        preview = Image.new('RGB', (16*10, 16*9), '#101010')
        for i in range(90):
            for y in range(16):
                for x in range(16):
                    if words[i*16+y] & (1 << (15-x)):
                        preview.putpixel(((i % 10)*16+x, (i//10)*16+y), (255,255,0))
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        preview.resize((640,512), Image.Resampling.NEAREST).save(args.preview)
    print('ALL PASS gen_zh_font: 90 glyphs, 1440 words; first 512 words unchanged')


if __name__ == '__main__':
    main()
