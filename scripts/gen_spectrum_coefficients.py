"""Reproducible, embedded Q1.15 FFT coefficients. No runtime file reads."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
def q15(value):
    return max(-32768, min(32767, round(value*32768))) & 0xffff

def generate():
    lines = ['// Generated by scripts/gen_spectrum_coefficients.py; Q1.15.',
             'module spectrum_coefficients(input clk,input [6:0] tw_address,',
             ' input [7:0] window_address,output reg signed [15:0] tw_real,tw_imag,window);',
             ' // Small 16-entry logic tables avoid TD promoting a wide ROM to BRAM.',
             " wire [6:0] wa=window_address[7]?~window_address[6:0]:window_address[6:0];"]
    twiddle=[]
    for i in range(128):
        angle = -2*math.pi*i/256
        twiddle.append((q15(math.cos(angle))<<16)|q15(math.sin(angle)))
    hann=[q15((1-math.cos(2*math.pi*i/255))/2) for i in range(128)]
    for name,width,values,address in [('tw',32,twiddle,'tw_address'),('win',16,hann,'wa')]:
        for group in range(8):
            fn=f'{name}{group}'
            lines += [f' function [{width-1}:0] {fn};', '  input [3:0] a;begin case(a)']
            for offset in range(16):
                lines.append(f"   4'd{offset}:{fn}={width}'h{values[group*16+offset]:0{width//4}x};")
            lines += ['  endcase end endfunction']
        lines += [f' reg [{width-1}:0] {name}_value;',f' always @*begin case({address}[6:4])']
        for group in range(8):
            lines.append(f"  3'd{group}:{name}_value={name}{group}({address}[3:0]);")
        lines += [' endcase end']
    lines += [' always @(posedge clk)begin',
              '  {tw_real,tw_imag}<=tw_value;',
              '  window<=win_value;',
              ' end', 'endmodule', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    path = ROOT/'src/modules/audio/spectrum_coefficients.v'
    path.write_text(generate(), encoding='ascii')
    print('Generated',path)
